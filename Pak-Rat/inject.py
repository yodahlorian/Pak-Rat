def _clone_exemplar(ex: dict, item: str, mesh: str,
                    src_ua: Path, src_ux: Path, stage: Path,
                    thumb_token: str | None = None,
                    extra_renames: list[str] | None = None) -> dict:
    """RE-SERIALISE the exemplar into a NEW package identity (fresh PackageGuid +
    PackageSource + FolderName) pointing at the user's cooked mesh, via
    relink.clone (in-process, any-length exact name-map renames). Stages
    <item>.uasset/.uexp under the pak tree. When `thumb_token` is given, also
    repoints the catalogue thumbnail to the item's own texture (custom thumbnail).
    Returns {pkg_game, cls, ua, thumb_path}."""
    base = ex["self_path"].rsplit("/", 2)[0]            # .../decoration
    new_self = f"{base}/{item}/{item}"
    new_mesh_path = f"{ex['mesh_path'].rsplit('/', 1)[0]}/{mesh}"
    game_dir = new_self.rsplit("/", 1)[0]              # .../decoration/<item>
    mount_dir = "RetroRewind/Content/" + game_dir[len("/Game/"):]
    dest = stage / Path(*mount_dir.split("/"))
    dest.mkdir(parents=True, exist_ok=True)
    out_ua = dest / f"{item}.uasset"

    # trailing rename pairs: mesh package ref + mesh object name (renamed to the
    # user's cooked mesh) — UNLESS keep_mesh, where the clone reuses the vanilla
    # mesh (equipment: no user model), so the mesh ref must be left untouched.
    extra = [] if ex.get("keep_mesh") else [ex["mesh_path"], new_mesh_path,
                                            ex["mesh_name"], mesh]
    new_thumb_path = None
    if thumb_token:
        new_thumb_path = f"{game_dir}/{thumb_token}"
        extra += [ex["thumb_path"], new_thumb_path, ex["thumb_name"], thumb_token]

    # Equipment: repoint the BP's colour-MI references to the cloned MIs (old/new
    # package-path + object-leaf pairs computed by _stage_equipment_textures).
    if extra_renames:
        extra += list(extra_renames)

    relink.clone(src_ua, out_ua, ex["self_path"], new_self,
                 ex["class_token"], f"{item}_C", *extra)
    return {"pkg_game": new_self, "cls": f"{new_self}.{item}_C", "ua": out_ua,
            "thumb_path": new_thumb_path}


def _clone_container_box(ex: dict, item: str, product_self: str, stage: Path) -> dict:
    """TIER 2 (snack/drink/toy) — clone the vending BOX (the actual Container
    catalogue item) to a new identity, repoint the product-class it references to
    the just-cloned product (<item>_C at `product_self`), then box_repoint EVERY
    shelf slot to that product so the box shows/dispenses only the custom product.
    Returns {pkg_game, cls, ua} for the BOX — the entry that gets widget-registered.

    Assumes ex['box'] = {pak_dir, asset, self_path, class_token, product_class}. The
    box's name map holds the product class token AND the product's package path as
    imports; renaming both repoints the box's product import, then box_repoint fills
    all slots. (Rename strings VERIFIED present in the snack/toy/drink box name maps
    against the R: base pak 2026-07-07 — SnackBox_Snack_C / ToysBox_C / DrinkBox_C and
    each product class + package path all resolve.)"""
    box = ex["box"]
    box_item = item + "Box"
    box_base = box["self_path"].rsplit("/", 1)[0]              # .../Snack
    new_box_self = f"{box_base}/{box_item}/{box_item}"
    mount_dir = "RetroRewind/Content/" + new_box_self.rsplit("/", 1)[0][len("/Game/"):]
    dest = stage / Path(*mount_dir.split("/"))
    dest.mkdir(parents=True, exist_ok=True)
    out_ua = dest / f"{box_item}.uasset"

    import tempfile
    tmp = Path(tempfile.mkdtemp(prefix="pakrat_box_"))
    core._repak("unpack", "-f", "-o", str(tmp),
                "-i", f"{box['pak_dir']}/{box['asset']}.uasset",
                "-i", f"{box['pak_dir']}/{box['asset']}.uexp",
                str(core.base_pak()))
    src_ua = tmp / Path(*box["pak_dir"].split("/")) / f"{box['asset']}.uasset"

    # New box identity + repoint the referenced product (class token + package path)
    # to the cloned product, so slot 1 already points at it; box_repoint does the rest.
    relink.clone(src_ua, out_ua, box["self_path"], new_box_self,
                 box["class_token"], f"{box_item}_C",
                 box["product_class"], f"{item}_C",
                 ex["self_path"], product_self)
    relink.box_repoint(out_ua, out_ua, f"Default__{box_item}_C", f"{item}_C")
    return {"pkg_game": new_box_self, "cls": f"{new_box_self}.{box_item}_C", "ua": out_ua}


def _cook_user_mesh(env: "cook.CookEnv", fbx: str, mesh_token: str,
                    stage: Path, progress=None, placement: str | None = None,
                    mi_paths: "list[str] | None" = None) -> int:
    """Import+cook the user FBX to /Game/.../meshes/<mesh_token>, retarget its
    material slots onto `mi_paths` (the game/cloned MIs, staged separately by
    _stage_mesh_material), and stage the mesh. Returns files staged (0 => cook
    produced nothing)."""
    log = cook.home() / "inject_cook.log"
    try:
        log.unlink()
    except Exception:
        pass
    # Normalise ANY non-FBX source (incl. .uemodel from FModel) to FBX via Blender
    # before the UE import — UE's importer only reads FBX/OBJ. Pass-through for .fbx.
    fbx = cook.convert_to_fbx(env, fbx, progress=progress)
    # Wall-mounted items: shift the pivot to the mesh's back face so it mounts flush
    # against the wall (not half-buried) and its collision no longer penetrates.
    if placement == "wall":
        fbx = cook.wall_recenter(env, fbx, progress=progress)
    # The user's material textures ride on cloned MIs staged upstream
    # (_stage_mesh_material); the cook retargets the mesh's slots onto them via stub
    # MICs at those paths — the single texture path, no Blender material bake here.
    script = cook.project_dir() / "pakrat_mesh_import.py"
    script.write_text(_MESH_COOK_SCRIPT % {
        "log": str(log), "fbx": fbx, "pkg": MESH_ROOT, "name": mesh_token,
        "place": placement or "", "mis": repr(list(mi_paths or []))},
        encoding="utf-8")
    if progress:
        progress(f"Importing mesh '{mesh_token}'…", None)
    cook._ue(env, f"-ExecutePythonScript={script}")
    if progress:
        progress("Cooking mesh…", None)
    cook._ue(env, "-run=cook", "-targetplatform=Windows", "-unversioned",
             "-cookall", "-nozenstore")
    cooked_root = cook.project_dir() / "Saved" / "Cooked"
    matches = sorted(cooked_root.rglob(mesh_token + ".uasset")) if cooked_root.is_dir() else []
    if not matches:
        return 0
    src = matches[0]
    mount = "RetroRewind/Content/" + MESH_ROOT[len("/Game/"):]
    dest = stage / Path(*mount.split("/"))
    dest.mkdir(parents=True, exist_ok=True)
    n = 0
    for f in src.parent.glob(mesh_token + ".*"):
        if f.suffix in (".uasset", ".uexp", ".ubulk"):
            shutil.copy2(f, dest / f.name); n += 1
    return n


