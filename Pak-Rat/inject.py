    """Cook the user's mesh + clone the type's exemplar to point at it, then stamp
    the item's CDO (custom name key + price) LENGTH-NEUTRALLY. Optional `thumbnail`
    gives a custom catalogue icon (best-effort; falls back to the default icon).
    `texture` (mesh skin) is deferred — bake it into the model. Returns the manifest
    entry {pkg, cls, name, category, price}."""
    ex = get_exemplar(exemplar, category)
    item, mesh = _slot_tokens(ex, index)
    keep_mesh = bool(ex.get("keep_mesh"))
    # Resolve the user's texture SET into {bc,n,ram}; omitted Normal/RAM are neutral-
    # filled (D3) so a replace never keeps a stale map. `bc` is the base-colour skin.
    mset = _resolve_maps(maps, stage)
    bc = mset.get("bc")
    # Equipment (keep_mesh) clones the base machine WHOLE — vanilla mesh + materials,
    # no user model — so there is no FBX to cook. Everything else cooks the user mesh.
    if not keep_mesh:
        # Give the cooked mesh the GAME's material with the USER's textures: clone the
        # exemplar mesh's MIs, repoint their bc/n/ram/ao to the user's maps (the single
        # texture path). With no user maps, retarget to the vanilla MIs as-is so the
        # mesh still wears the real game material (not the default checker).
        has_maps = bool(mset.get("bc") or mset.get("n") or mset.get("ram"))
        bp_material_renames: list[str] = []
        try:
            if has_maps:
                if progress:
                    progress("Applying your material textures…", None)
                mi_paths = _stage_mesh_material(ex, item, mset, stage)

                # The exemplar Blueprint may carry OverrideMaterials entries that
                # still point at the source mesh's materials.  Those overrides win
                # over the material slots cooked onto the replacement mesh, so also
                # repoint every source-material package/object reference in the BP
                # clone to the corresponding per-item cloned MI.
                source_mesh_mount = ex["mesh_path"].replace(
                    "/Game/", "RetroRewind/Content/", 1)
                source_mis = cook.resolve_mesh_materials(source_mesh_mount)
                for old_mi, new_mi in zip(source_mis, mi_paths):
                    bp_material_renames += [
                        old_mi, new_mi,
                        old_mi.rsplit("/", 1)[-1],
                        new_mi.rsplit("/", 1)[-1],
                    ]
            else:
                mesh_mount = ex["mesh_path"].replace("/Game/", "RetroRewind/Content/", 1)
                mi_paths = cook.resolve_mesh_materials(mesh_mount)
        except Exception as e:
            if progress:
                progress(f"Material textures skipped ({e}); using the mesh's own.", None)
            mi_paths = []
        if _cook_user_mesh(env, fbx, mesh, stage, progress=progress,
                           placement=ex.get("placement"), mi_paths=mi_paths) == 0:
            raise RuntimeError(
                f"Cook produced no mesh for '{display_name}'. The UE cook step likely "
                "failed; see inject_cook.log / last_cook.log in the Pak Rat home folder.")

    # Custom mesh skin (texture):
    #  - Decoration/cooked items: handled above via _stage_mesh_material (game
    #    material cloned with the user's bc/n/ram) — nothing deferred here anymore.
    #  - Equipment (keep_mesh) WITH colour materials: reskin the body base-colour
    #    texture from the user's image and repoint the cloned colour MIs to it, so
    #    only this new machine is recoloured (the Arcade_D recipe). Best-effort:
    #    a reskin hiccup falls back to the vanilla skin, never fails the add.
    mi_renames: list[str] = list(locals().get("bp_material_renames", []))
    if not keep_mesh:
        pass
    else:
        # Equipment body/colour: additive per-item MI reskin where the colour MIs are
        # BP-reachable (arcade), else an in-place texture override (pinball).
        if bc and ex.get("color_materials"):
            try:
                if progress:
                    progress("Reskinning the machine's colour…", None)
                mi_renames = _stage_equipment_textures(ex, item, mset, stage)
            except Exception as e:
                if progress:
                    progress(f"Colour reskin skipped ({e}); keeping the vanilla skin.", None)
                mi_renames = []
        elif bc and ex.get("body_override"):
            try:
                if progress:
                    progress("Reskinning the machine's colour…", None)
                _reskin_override(ex["body_override"], bc, stage)
            except Exception as e:
                if progress:
                    progress(f"Colour reskin skipped ({e}); keeping the vanilla skin.", None)
        # Equipment screen/display: override the video-screen texture in place.
        if screen and ex.get("screen_texture"):
            try:
                if progress:
                    progress("Reskinning the screen…", None)
                _reskin_override(ex["screen_texture"], screen, stage)
            except Exception as e:
                if progress:
                    progress(f"Screen reskin skipped ({e}); keeping the vanilla screen.", None)

    import tempfile
    tmp = Path(tempfile.mkdtemp(prefix="pakrat_ex_"))
    src_ua, src_ux = _extract_exemplar(ex, tmp)

    # Custom thumbnail — build it FIRST; only repoint the item to it if it fully
    # succeeds, otherwise keep the exemplar's icon (a real icon beats a blank one).
    # Best-effort and NON-FATAL: a thumbnail hiccup must never fail the whole add.
    thumb_token = None
    if thumbnail:
        try:
            if progress:
                progress("Building custom thumbnail…", None)
            tok = f"T_{item}_T"
            base = ex["self_path"].rsplit("/", 2)[0]            # .../decoration
            new_thumb_game = f"{base}/{item}/{tok}"             # matches _clone_exemplar
            _stage_custom_thumbnail(ex, thumbnail, new_thumb_game, tok, stage)
            thumb_token = tok                                   # success -> clone repoints to it
        except Exception as e:
            if progress:
                progress(f"Custom thumbnail skipped ({e}); using the default icon.", None)

    cloned = _clone_exemplar(ex, item, mesh, src_ua, src_ux, stage,
                             thumb_token=thumb_token, extra_renames=mi_renames)

    # CDO: swap the localisation title-key (name resolves via the StringTable set in
    # run_add_pipeline) AND set the price — both length-neutral in-place (the #6/#7
    # fix: token length was chosen so the key byte length is unchanged).
    p = float(price) if price is not None else ex.get("default_price", 0.0)
    is_container = ex.get("category") == "Container"
    if keep_mesh:
        # Equipment CDO layout differs from decorations (its title key is a
        # Statistic-LevelUp key, same byte length as Interface_ModKit_<item>_Title).
        # A swap that can't be applied length-neutrally must NOT fail the whole add —
        # fall back to the vanilla machine name/price. (In-game name = Yodah confirms.)
        try:
            relink.setcdo(cloned["ua"], cloned["ua"], f"Default__{item}_C",
                          _title_key(item), price=p)
        except Exception as e:
            if progress:
                progress(f"Custom equipment name/price skipped ({e}); vanilla kept.", None)
    elif is_container:
        # snack products own a title-key → custom NAME (name-only: a price would corrupt
        # the thumbnail refs that sit right after the key). toy/drink products inherit
        # from a *_Base with NO title-key → skip setcdo entirely (derived name), else
        # _find_title_key raises and sinks the whole add.
        if ex.get("cdo_title_key"):
            relink.setcdo(cloned["ua"], cloned["ua"], f"Default__{item}_C",
                          _title_key(item), price=None)
    else:
        relink.setcdo(cloned["ua"], cloned["ua"], f"Default__{item}_C",
                      _title_key(item), price=p)

    # TIER 2 (snack/drink/toy): the CATALOGUE item is the vending BOX, not the product.
    # Clone the box, repoint its product-class array to the just-cloned product, and
    # register the BOX — so the box shows/dispenses the user's custom product.
    if is_container and ex.get("box"):
        if progress:
            progress("Building the vending box…", None)
        box = _clone_container_box(ex, item, cloned["pkg_game"], stage)
        return {"pkg": box["pkg_game"], "cls": box["cls"], "name": display_name,
                "category": ex["category"], "price": p,
                "sibling": ex.get("widget_sibling"),
                # NAME is stamped on the PRODUCT CDO (Interface_ModKit_<item>_Title), not
                # the box — carry the product token so the StringTable binds to it. Only
                # snack products have a title-key; toy/drink are derived (name_token None).
                "name_token": item if ex.get("cdo_title_key") else None}

    return {"pkg": cloned["pkg_game"], "cls": cloned["cls"], "name": display_name,
            "category": ex["category"], "price": p,
            "sibling": ex.get("widget_sibling")}


