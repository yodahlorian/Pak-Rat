def _neutral_png(kind: str, size: "tuple[int, int]", dest: Path) -> Path:
    """Write a NEUTRAL default map PNG so a replaced material never keeps a stale map
    (D3). 'normal' -> flat normal RGB(128,128,255); 'ram' -> packed mask
    R=roughness(160) / G=AO white(255) / B=metallic(0); 'ao' -> white(255,255,255)
    (no occlusion — the exemplar's baked AO is meaningless on the user's mesh)."""
    from PIL import Image
    if kind == "normal":
        color = (128, 128, 255)
    elif kind == "ao":
        color = (255, 255, 255)
    else:                                   # ram
        color = (160, 255, 0)
    dest.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", (int(size[0]), int(size[1])), color).save(dest)
    return dest


def _resolve_maps(maps: "dict | str | None", stage: Path) -> "dict":
    """Normalise the caller's texture-set into {'bc','n','ram'} of file paths and
    enforce D3: if a Base Color (a real skin replace) is given, any omitted Normal /
    Packed-mask slot is filled with a generated NEUTRAL default so the material never
    inherits a stale map. Accepts a legacy single-path str (treated as base colour)."""
    if maps is None:
        return {"bc": None, "n": None, "ram": None}
    if isinstance(maps, str):
        maps = {"bc": maps}
    out = {"bc": maps.get("bc"), "n": maps.get("n"), "ram": maps.get("ram"),
           "ao": None}
    # Size the neutrals to the base-colour image when we have one, else a safe 1024².
    size = (1024, 1024)
    if out["bc"]:
        try:
            from PIL import Image
            with Image.open(out["bc"]) as im:
                size = im.size
        except Exception:
            pass
    if out["bc"] or out["n"] or out["ram"]:
        # Neutrals are SOURCE images for the inject — write them to a temp dir, never
        # under `stage` (that would pack the raw PNG into the mod). Omitted Normal/RAM
        # get neutral defaults; AO is ALWAYS neutral (D3 — the exemplar's baked AO is
        # meaningless on the user's mesh, so we never inherit it).
        import tempfile
        nd = Path(tempfile.mkdtemp(prefix="pakrat_neutral_"))
        if not out["n"]:
            out["n"] = str(_neutral_png("normal", size, nd / "neutral_n.png"))
        if not out["ram"]:
            out["ram"] = str(_neutral_png("ram", size, nd / "neutral_ram.png"))
        out["ao"] = str(_neutral_png("ao", size, nd / "neutral_ao.png"))
    return out


def _fit_token(seed: str, length: int) -> str:
    """Return a deterministic Unreal-safe token of exactly ``length`` characters."""
    import hashlib
    if length < 1:
        raise RuntimeError("cannot create an empty Unreal name token")
    digest = hashlib.sha1(seed.encode("utf-8")).hexdigest()
    token = (seed.replace("-", "_").replace(" ", "_") + "_" + digest)
    token = "".join(c if (c.isalnum() or c == "_") else "_" for c in token)
    if not token[0].isalpha() and token[0] != "_":
        token = "P" + token
    return (token + "_" * length)[:length]


def _length_neutral_texture_identity(old_game: str, item: str,
                                     mi_i: int, suffix: str) -> tuple[str, str]:
    """Create a unique package path/object name with the SAME byte lengths as the
    donor identity.  Equal-length replacement lets us rename the already-injected
    texture in-place without asking UAssetAPI to reserialize its mip/UBULK data.
    """
    old_leaf = old_game.rsplit("/", 1)[-1]
    leaf = _fit_token(f"T_PR_{item}_{mi_i:02d}_{suffix}", len(old_leaf))
    # Keep /Game/ and one generated folder.  The folder is padded so the complete
    # package path has exactly the donor path's ASCII byte length.
    folder_len = len(old_game) - len("/Game/") - 1 - len(leaf)
    if folder_len < 1:
        raise RuntimeError(f"donor texture path is too short to clone safely: {old_game}")
    folder = _fit_token(f"PakRat_{item}_{mi_i:02d}_{suffix}", folder_len)
    new_game = f"/Game/{folder}/{leaf}"
    if len(new_game.encode("ascii")) != len(old_game.encode("ascii")):
        raise RuntimeError("internal error creating length-neutral texture identity")
    return new_game, leaf


def _replace_equal_length(path: Path, pairs: list[tuple[str, str]]) -> int:
    """Patch exact ASCII name-map strings without shifting a cooked package.
    Returns the number of old-string occurrences replaced.
    """
    if not path.is_file():
        return 0
    data = path.read_bytes()
    count = 0
    for old, new in pairs:
        ob = old.encode("ascii")
        nb = new.encode("ascii")
        if len(ob) != len(nb):
            raise RuntimeError(f"non length-neutral rename: {old!r} -> {new!r}")
        n = data.count(ob)
        if n:
            data = data.replace(ob, nb)
            count += n
    path.write_bytes(data)
    return count


def _reskin_and_stage(base_mount: str, user_image: str, new_game_path: str,
                      old_leaf: str, new_leaf: str, stage: Path) -> tuple[str, str]:
    """Inject first, then rename with LENGTH-NEUTRAL byte edits.

    The proven MI patch worked because it injected the correct pixels and then cloned
    the texture, but UAssetAPI's clone rewrite discarded the large external mip data,
    leaving only the donor's 64x64 inline mip.  Cloning before injection preserved
    mips but broke the material reference.  This version keeps the proven order while
    avoiding UAssetAPI for the texture package itself: it injects the full-resolution
    image, copies every sidecar, and edits only equal-length package/object strings.
    No offsets move and .ubulk is preserved byte-for-byte.

    Returns the actual cloned /Game path and leaf used by the Material Instance.
    """
    spec = core.prepare_target(base_mount)
    try:
        injected = Path(spec.work_dir) / "reskin"
        core.replace_texture(base_mount, user_image, injected, spec=spec,
                             preserve_resolution=True)
        injected_ua = injected / f"{old_leaf}.uasset"
        if not injected_ua.is_file():
            raise RuntimeError("injector produced no output texture")

        old_game = base_mount.replace("RetroRewind/Content/", "/Game/", 1)
        # Derive the suffix/index from the requested identity, but generate an alias
        # whose package and object strings exactly match the donor lengths.
        try:
            mi_i = int(new_leaf.rsplit("_", 2)[-2])
        except Exception:
            mi_i = 0
        suffix = new_leaf.rsplit("_", 1)[-1]
        actual_game, actual_leaf = _length_neutral_texture_identity(
            old_game, new_leaf, mi_i, suffix)

        mount_dir = "RetroRewind/Content/" + actual_game.rsplit("/", 1)[0][len("/Game/"):]
        dest = stage / Path(*mount_dir.split("/"))
        dest.mkdir(parents=True, exist_ok=True)

        copied = []
        for ext in ("uasset", "uexp", "ubulk", "uptnl"):
            src = injected / f"{old_leaf}.{ext}"
            if not src.is_file():
                continue
            dst = dest / f"{actual_leaf}.{ext}"
            shutil.copy2(src, dst)
            copied.append(ext)

        if "uasset" not in copied:
            raise RuntimeError("failed to stage cloned texture")

        pairs = [(old_game, actual_game), (old_leaf, actual_leaf)]
        # Identity strings live in the package/name-map data, not the bulk pixels.
        # Patch only metadata-bearing files; leave .ubulk/.uptnl untouched.
        rename_hits = 0
        for ext in ("uasset", "uexp"):
            f = dest / f"{actual_leaf}.{ext}"
            rename_hits += _replace_equal_length(f, pairs)
        if rename_hits == 0:
            raise RuntimeError(
                f"texture identity was not found in {old_leaf}.uasset/.uexp")

        print(f"Pak Rat texture: {old_leaf} -> {actual_leaf}; "
              f"sidecars={copied}; rename_hits={rename_hits}")
        return actual_game, actual_leaf
    finally:
        core.cleanup_target(spec)


def _stage_custom_thumbnail(ex: dict, user_image: str, new_thumb_game_path: str,
                            thumb_token: str, stage: Path) -> None:
    """Build the item's catalogue thumbnail from `user_image`, re-identitied to the
    item's own thumbnail package path (the clone already repointed the CDO to it)."""
    _reskin_and_stage(
        base_mount=ex["thumb_path"].replace("/Game/", "RetroRewind/Content/", 1),
        user_image=user_image, new_game_path=new_thumb_game_path,
        old_leaf=ex["thumb_name"], new_leaf=thumb_token, stage=stage)


def _extract_game_asset(game_path: str, dest: Path) -> Path:
    """repak-unpack a single asset (.uasset + .uexp) by /Game path from the base
    pak. Returns the extracted .uasset. Used to pull the colour MIs to clone."""
    mount = game_path.replace("/Game/", "RetroRewind/Content/", 1)
    pak_dir, leaf = mount.rsplit("/", 1)
    core._repak("unpack", "-f", "-o", str(dest),
                "-i", f"{pak_dir}/{leaf}.uasset",
                "-i", f"{pak_dir}/{leaf}.uexp",
                str(core.base_pak()))
    return dest / Path(*pak_dir.split("/")) / f"{leaf}.uasset"


def _stage_equipment_textures(ex: dict, item: str, mset: "dict",
                              stage: Path) -> list[str]:
    """Recolour ONE equipment machine additively (the Arcade_D recipe): reskin the
    body base-colour texture from the user's image, then clone the colour MIs to new
    identities under the item's own /Game dir — the body MI repointed to the new
    texture. Returns the BP name-map rename pairs (old MI package-path + object-leaf
    -> new) so the cloned Blueprint references the new MIs (and thus the new skin)."""
    import tempfile
    base = ex["self_path"].rsplit("/", 2)[0]           # /Game/.../prop
    game_dir = f"{base}/{item}"                         # /Game/.../prop/<item>

    # 1) new body texture from the user's image, re-identitied under the item dir.
    body = ex["body_texture"]
    new_body_leaf = f"T_{item}_bc"
    new_body_game = f"{game_dir}/{new_body_leaf}"
    _reskin_and_stage(
        base_mount=body["path"].replace("/Game/", "RetroRewind/Content/", 1),
        user_image=mset["bc"], new_game_path=new_body_game,
        old_leaf=body["name"], new_leaf=new_body_leaf, stage=stage)

    # 2) clone each colour MI to a fresh identity under the item dir; the body MI
    #    also repoints its base-colour texture ref (path + leaf) to the new texture.
    renames: list[str] = []
    for i, mi in enumerate(ex["color_materials"]):
        new_mi_leaf = f"MI_{item}_{i:02d}"
        new_mi_game = f"{game_dir}/{new_mi_leaf}"
        tmp = Path(tempfile.mkdtemp(prefix="pakrat_mi_"))
        mi_ua = _extract_game_asset(mi["path"], tmp)
        mount_dir = "RetroRewind/Content/" + new_mi_game.rsplit("/", 1)[0][len("/Game/"):]
        dest = stage / Path(*mount_dir.split("/"))
        dest.mkdir(parents=True, exist_ok=True)
        out_ua = dest / f"{new_mi_leaf}.uasset"
        # an MI has no _C class/CDO -> the leaf name rides the old_cls/new_cls slot.
        tex_pairs = ([body["path"], new_body_game, body["name"], new_body_leaf]
                     if mi.get("body") else [])
        relink.clone(mi_ua, out_ua, mi["path"], new_mi_game,
                     mi["name"], new_mi_leaf, *tex_pairs)
        renames += [mi["path"], new_mi_game, mi["name"], new_mi_leaf]
    return renames


def _stage_mesh_material(ex: dict, item: str, mset: "dict", stage: Path) -> list[str]:
    """Give a cooked user mesh the GAME's material wearing the USER's textures (the
    robust texture path). For each material the exemplar's mesh uses: clone it to a
    per-item identity, and for each of its bc / n / ram / ao texture slots inject the
    user's matching map (omitted Normal/RAM -> neutral; AO always neutral, D3 — never
    inherit the exemplar's baked maps). The shared vanilla textures are never touched
    (clone-mode, via the single texture primitive). Returns the cloned MI /Game paths
    so the cook can retarget the cooked mesh's material slots onto them."""
    import tempfile
    # The Blueprint's source mesh and the material donor are separate concerns.
    # `mesh_path` must remain the mesh reference actually present in the cloned BP
    # so _clone_exemplar can replace it. `material_mesh_path` may point to a cleaner
    # self-contained asset whose material owns local bc/n/ram textures.
    material_mesh_path = ex.get("material_mesh_path", ex["mesh_path"])
    mesh_mount = material_mesh_path.replace("/Game/", "RetroRewind/Content/", 1)
    mis = cook.resolve_mesh_materials(mesh_mount)          # /Game/.../MI paths
    if not mis:
        return []
    base = ex["self_path"].rsplit("/", 2)[0]              # /Game/.../<prop parent>
    game_dir = f"{base}/{item}"                            # per-item dir
    slot_img = {"bc": mset.get("bc"), "n": mset.get("n"),
                "ram": mset.get("ram"), "ao": mset.get("ao")}
    new_mis: list[str] = []
    for mi_i, mi_game in enumerate(mis):
        tmp = Path(tempfile.mkdtemp(prefix="pakrat_mi_"))
        mi_ua = str(_extract_game_asset(mi_game, tmp))
        # Discover the texture-object references stored in the active Material
        # Instance parameter table.  The Chair uses shared library textures, but
        # those references still live in MI_Chair_A_01 and must be redirected.
        tex_refs: dict = {}
        for ref in core._scan_refs(mi_ua, mi_ua[:-7] + ".uexp"):
            if core._classify(ref) == "texture":
                ref_game = cook.mount_to_game(ref)
                suf = ref_game.rsplit("_", 1)[-1].lower()
                # Packed maps in this project are normally named *_ram.  Accept a
                # *_packed alias too so the redirection remains explicit.
                if suf == "packed":
                    suf = "ram"
                if suf in ("bc", "n", "ram", "ao"):
                    tex_refs.setdefault(suf, ref_game)
        if not tex_refs:
            raise RuntimeError(
                f"No Base/Normal/RAM/AO parameter textures were found in {mi_game}")
        # reskin each slot to a per-item texture identity + collect MI rename pairs
        tex_pairs: list[str] = []
        for suf, old_game in tex_refs.items():
            img = slot_img.get(suf)
            if not img:
                continue                                  # slot we don't drive
            old_mount = old_game.replace("/Game/", "RetroRewind/Content/", 1)
            old_leaf = old_game.rsplit("/", 1)[-1]
            new_leaf = f"T_{item}_{mi_i:02d}_{suf}"
            new_tex_game = f"{game_dir}/{new_leaf}"
            actual_game, actual_leaf = _reskin_and_stage(
                old_mount, img, new_tex_game, old_leaf, new_leaf, stage)
            tex_pairs += [old_game, actual_game, old_leaf, actual_leaf]
        if not tex_pairs:
            raise RuntimeError(
                f"No material texture parameters were redirected in {mi_game}")
        # Clone the active MI to a per-item identity. relink.clone rewrites both the
        # imported package path and object leaf for every discovered parameter
        # texture, which changes the MI parameter values rather than merely creating
        # unused texture assets.
        new_mi_leaf = f"MI_{item}_{mi_i:02d}"
        new_mi_game = f"{game_dir}/{new_mi_leaf}"
        mount_dir = "RetroRewind/Content/" + new_mi_game.rsplit("/", 1)[0][len("/Game/"):]
        dest = stage / Path(*mount_dir.split("/"))
        dest.mkdir(parents=True, exist_ok=True)
        out_ua = dest / f"{new_mi_leaf}.uasset"
        mi_leaf = mi_game.rsplit("/", 1)[-1]
        relink.clone(Path(mi_ua), out_ua, mi_game, new_mi_game,
                     mi_leaf, new_mi_leaf, *tex_pairs)
        new_mis.append(new_mi_game)
    return new_mis


def _reskin_override(tex: dict, user_image: str, stage: Path) -> None:
    """OVERRIDE-mode texture swap: inject the user's image and stage it at the
    texture's OWN vanilla path (the pak globally supplies new pixels — the PacMan
    mechanism). Used where the texture is applied by Blueprint/SKU logic rather than
    a clone-reachable MI (arcade screen, pinball body). Delegates to core.stage_texture
    (the single texture-replacement primitive, in-place)."""
    base_mount = tex["path"].replace("/Game/", "RetroRewind/Content/", 1)
    core.stage_texture(base_mount, user_image, stage)


def run_add_pipeline(items: list[dict], progress=None, reset: bool = False) -> dict:
    """
    items: [{'fbx': path, 'name': str, 'category': 'Decoration'}, …]
    Per item: cook the user's mesh, then RE-SERIALISE a fresh-identity clone of the
    type's exemplar pointing at that mesh. Then extract the vanilla catalogue widget
    and CHAIN-insert every manifest item's class into its product-class bytecode —
    NATIVE registration, NO UE4SS/Lua. Each item's staged files are kept in a permanent
    asset library (see asset_library) and EVERY run rebuilds ONE fixed-name V8B pak from
    the whole library — widget + StringTable + all clones + meshes + thumbnails — then
    overwrites the previous pak on deploy. So adds accumulate without bound and no earlier
    item is dropped. Manifest is additive across runs (it drives the widget insert).
    Returns {'pak': path, 'ini': path, 'items_by_cat': {...}}.
    """
    import tempfile

    def say(m, p=None):
        if progress:
            progress(m, p)

    env = cook.setup(progress=progress)   # UE cooker (for the user's mesh)

    work = Path(tempfile.mkdtemp(prefix="pakrat_add_"))
    stage = work / "stage"
    stage.mkdir(parents=True, exist_ok=True)      # repak needs the dir to exist

    # Global, ever-increasing slot index keeps every added class name unique.
    if reset:                       # #5: start from a clean catalogue on request
        reset_additions()
    existing = manifest_items()
    base_index = sum(len(v) for v in existing.values())
    built = []
    for i, it in enumerate(items):
        entry = build_added_item(
            env, it["fbx"], it.get("name") or f"PakRatItem{i}",
            it.get("category", "Decoration"), base_index + i, stage,
            price=it.get("price"), maps=it.get("maps"),
            thumbnail=it.get("thumbnail"), progress=progress,
            exemplar=it.get("exemplar"), screen=it.get("screen"))
        built.append(entry)

    # Persist THIS run's freshly-staged item files (mesh + CDO + thumbnail) into the
    # permanent library, then pull the ENTIRE library back into the stage — so the pak
    # we pack below carries every item ever added, not just this run's. This is what
    # stops a second Add from dropping the first item's assets. (`stage` holds only the
    # new items' files at this point; the widget + StringTable are staged further down.)
    lib = asset_library()
    _merge_tree(stage, lib)      # new items -> library (accumulate, unique paths)
    _merge_tree(lib, stage)      # whole library -> stage (older items restored)

    # Merge new items into the manifest (additive) — it drives the widget insert.
    items_by_cat = existing
    for e in built:
        items_by_cat.setdefault(e["category"], []).append(
            {"pkg": e["pkg"], "cls": e["cls"], "name": e["name"],
             "price": e.get("price"), "sibling": e.get("sibling"),
             "name_token": e.get("name_token")})

    # Register EVERY manifest item natively into the catalogue widget: start from a
    # fresh vanilla widget, chain one insert per item (each output feeds the next).
    say("Registering into the catalogue widget…", None)
    wtmp = Path(tempfile.mkdtemp(prefix="pakrat_wid_"))
    cur_ua, _ = _extract_widget(wtmp)
    n = 0
    for cat, lst in items_by_cat.items():
        fn, def_sib = CAT_WIDGET.get(cat, CAT_WIDGET["Decoration"])
        for it in lst:
            out_ua = wtmp / f"widget_{n}.uasset"
            # widget_insert wants the LEAF class name (P…_C), not the full object
            # path stored in it["cls"] (…/P.P…_C) — the import ObjectName + its
            # Default__<leaf> CDO import derive from the leaf.
            leaf_cls = it["cls"].rsplit(".", 1)[-1]
            # Per-item sibling (wall items anchor on PosterFrame_C; equipment on
            # Pinball-Machine_A_C), falling back to the category default.
            sib = it.get("sibling") or def_sib
            relink.widget_insert(cur_ua, out_ua, it["pkg"], leaf_cls, sib, fn)
            cur_ua = out_ua
            n += 1
    wdest = stage / Path(*WIDGET_PAK_DIR.split("/"))
    wdest.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(cur_ua, wdest / f"{WIDGET_ASSET}.uasset")
    shutil.copyfile(cur_ua.with_suffix(".uexp"), wdest / f"{WIDGET_ASSET}.uexp")

    # Custom display NAMES: rebuild the Interface StringTable from vanilla, add every
    # manifest item's per-item title key -> its display name, and stage it in the pak
    # (Grok's proven mechanism; the CDO title key set above resolves against this).
    say("Applying custom names…", None)
    stmp = Path(tempfile.mkdtemp(prefix="pakrat_st_"))
    cur_st, _ = _extract_interface(stmp)
    m = 0
    for cat, lst in items_by_cat.items():
        for it in lst:
            # Container items register the BOX but stamp the name on the PRODUCT CDO
            # (Interface_ModKit_<product-token>_Title) — bind the StringTable to that
            # token, not the box's pkg leaf, so the custom product name resolves.
            item = it.get("name_token") or it["pkg"].rsplit("/", 1)[-1]   # Pxxxx
            out_st = stmp / f"st_{m}.uasset"
            relink.staddkey(cur_st, out_st, _title_key(item), it["name"])
            cur_st = out_st
            m += 1
    sdest = stage / Path(*INTERFACE_PAK_DIR.split("/"))
    sdest.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(cur_st, sdest / f"{INTERFACE_ASSET}.uasset")
    shutil.copyfile(cur_st.with_suffix(".uexp"), sdest / f"{INTERFACE_ASSET}.uexp")

    # Pack V8B (FNameBasedCompression, NO path-hash seed): required so genuinely NEW
    # package paths are discoverable by the loader (V11's path-hash index is not).
    say("Packaging .pak (V8B)…", None)
    # ONE fixed-name pak for all additions — deploy copies it by basename, so each
    # rebuild overwrites the previous pak in ~mods instead of piling up conflicting
    # catalogue widgets. Extend-in-place = unlimited add-ons.
    out_pak = work / ADDITIONS_PAK
    core._repak("pack", "--version", core.MESH_PAK_VERSION, "--mount-point",
                core.PAK_MOUNT, str(stage), str(out_pak))

    ini = save_manifest(items_by_cat)
    say("Done.", 100)
    return {"pak": str(out_pak), "ini": str(ini), "items_by_cat": items_by_cat}
